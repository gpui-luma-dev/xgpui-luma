//! Image Filters and the camera/control helpers shared by the media lab screens.
use gpui::{prelude::*, AnyElement, Context, MouseButton, MouseMoveEvent, div};
use lucide_svg_static::Icon;
use xgpui_luma_look_radix::{self as radix, Badge, BadgeVariant};
use xgpui_media::UploadStatus;

use super::{Action, FILTER_FIELDS, MIB, MediaPage, Parameter};
use crate::screen::{ChainPanel, ComparePane, Hero, LabCard, LabScreen, Param, ParametersPanel, labeled_control};

const TINTS: [&str; 3] = ["Identity", "Warm", "Cool"];
/// Tint mix amounts, matching `MediaPage::filter`.
const TINT_AMOUNTS: [f32; 3] = [0., 0.3, 0.3];
/// Fallback viewport width until the pane has been measured.
const DEFAULT_WIDTH: f32 = 560.;

const NOTE: &str = "Both panes draw the same source at the same size. The atlas path samples one level, so detail finer than a screen pixel folds into moiré. The media texture picks the mip level that matches the scale and averages away that detail.";
const CREDITS: &str = "Frequency field, Alpha edges and Color terrain are synthetic test images generated by the lab. Filters compose in order into one affine matrix in encoded sRGB and clamp once after the combined transform; the corner mask and opacity apply to the element afterwards. Upload size counts the source level only; a full mip chain adds about a third.";

impl MediaPage {
    pub(super) fn render_image_filters(&mut self, cx: &mut Context<Self>) -> impl IntoElement {
        self.sync_switches(cx);
        let width = self.viewport_width();
        let height = width * 2. / 3.;
        let scale = self.display_scale(width, height, cx);
        let screen = LabScreen::new("image-filters", self.look.clone())
            .crumb("xgpui-media", "Image Filters")
            .title("Image Filters")
            .lede("Compare one image drawn through the GPUI image atlas and through a dedicated mipmapped media texture, then adjust filters on the media texture only.")
            .hero(self.comparison_hero(width, height, scale, cx))
            .caption(self.state_line(scale));
        let screen = [Action::Sample, Action::Tint]
            .into_iter()
            .filter_map(|action| self.choice(action))
            .fold(screen, |screen, choice| screen.control(labeled_control(&self.look, choice.into_element())))
            .control(self.sweep_switch.clone());
        let screen = [Action::Open, Action::Reload, Action::Reset]
            .into_iter()
            .filter_map(|action| self.button(action))
            .fold(screen, LabScreen::action)
            .notice(self.error.as_ref().map(|error| format!("Media error: {error}")))
            .cards(self.status_cards(scale))
            .panels(self.filter_parameters(), self.filter_chain())
            .note(NOTE)
            .credits(CREDITS);
        self.camera_screen(screen, cx)
    }

    pub(super) fn camera_screen(&self, screen: LabScreen, cx: &mut Context<Self>) -> gpui::Div {
        // Dragging may leave the viewport, so the camera handlers wrap the whole page.
        div()
            .size_full()
            .on_mouse_move(cx.listener(|this, event: &MouseMoveEvent, _, cx| {
                if event.pressed_button != Some(MouseButton::Left) {
                    this.drag = None;
                } else if let Some((anchor, pan)) = this.drag {
                    let delta = event.position - anchor;
                    this.values[1] = pan[0] + f32::from(delta.x);
                    this.values[2] = pan[1] + f32::from(delta.y);
                    this.sync_camera(cx);
                    cx.notify();
                }
            }))
            .on_mouse_up(MouseButton::Left, cx.listener(|this, _, _, _| this.drag = None))
            .on_mouse_up_out(MouseButton::Left, cx.listener(|this, _, _, _| this.drag = None))
            .child(screen)
    }

    pub(super) fn comparison_hero(&self, width: f32, height: f32, scale: Option<f32>, cx: &mut Context<Self>) -> Hero {
        let downscaled = scale.is_some_and(|scale| scale < 1.);
        let levels = self.image.as_ref().map_or(0, |image| image.mip_count());
        let atlas = ComparePane::new("GPUI image atlas", self.compare_view(false, width, height, true, cx))
            .subtitle("Baseline · single level")
            .when(downscaled, |pane| pane.badge(self.badge("Aliasing", false)));
        let media = ComparePane::new("Mipmapped media texture", self.compare_view(true, width, height, true, cx))
            .subtitle(format!("Trilinear · {levels} levels"))
            .when(downscaled, |pane| pane.badge(self.badge("Filtered", true)));
        Hero::compare(atlas, media)
    }

    fn state_line(&self, scale: Option<f32>) -> String {
        let Some(sample) = self.fixtures.as_ref().map(|fixtures| &fixtures.samples[self.selected]) else {
            return "Generating test images…".into();
        };
        let active = self.filter_steps().iter().filter(|step| step.2).count();
        format!(
            "{} · {}×{} shown at {:.2}× · {active} of 7 filter steps active on the media texture",
            sample.name,
            sample.width,
            sample.height,
            scale.unwrap_or(0.)
        )
    }

    fn status_cards(&self, scale: Option<f32>) -> [LabCard; 4] {
        let image = self.image.as_ref();
        let sample = self.fixtures.as_ref().map(|fixtures| &fixtures.samples[self.selected]);
        let (status, ready) = match image.map(|image| image.upload_status()) {
            Some(UploadStatus::Ready) => ("Ready", true),
            Some(UploadStatus::Failed(_)) => ("Failed", false),
            Some(_) => ("Uploading", false),
            None => ("Loading", false),
        };
        let tint = TINT_AMOUNTS[self.tint_index];
        [
            LabCard::new("Image mode")
                .icon(Icon::Columns2)
                .subtitle("Atlas / mipmap")
                .badge(self.badge("Split", false))
                .values([
                    ("levels", image.map_or("—".into(), |image| image.mip_count().to_string())),
                    ("filter", "trilinear".into()),
                ]),
            LabCard::new("Upload")
                .icon(Icon::Upload)
                .subtitle("GPU texture")
                .badge(self.badge(status, ready))
                .values([
                    ("uploads", image.map_or("—".into(), |image| image.upload_count().to_string())),
                    (
                        "source",
                        image.map_or("—".into(), |image| {
                            format!("{:.2} MiB", image.payload_bytes() as f64 / MIB as f64)
                        }),
                    ),
                ]),
            LabCard::new("Sample")
                .icon(Icon::Target)
                .subtitle(sample.map_or("Generating…".into(), |sample| sample.name.clone()))
                .badge(self.badge(if self.selected < 3 { "Built-in" } else { "Imported" }, false))
                .values([
                    ("size", sample.map_or("—".into(), |sample| format!("{}×{}", sample.width, sample.height))),
                    ("scale", scale.map_or("—".into(), |scale| format!("{scale:.2}×"))),
                ]),
            LabCard::new("Tint")
                .icon(Icon::Droplet)
                .subtitle(format!("{} preset", TINTS[self.tint_index]))
                .badge(self.badge(if tint > 0. { "On" } else { "Off" }, tint > 0.))
                .values([("mix", format!("{tint:.2}")), ("scope", "media only".into())]),
        ]
    }

    fn filter_parameters(&self) -> ParametersPanel {
        let params = FILTER_FIELDS.into_iter().filter_map(|parameter| {
            let field = self.filter_fields.iter().find(|(id, _)| *id == parameter)?.1.clone();
            let slider = self.sliders.iter().find(|(id, _)| *id == parameter)?.1.clone();
            Some(Param::new(parameter.config().0, field, slider).range(parameter.range_label()))
        });
        ParametersPanel::new("Filter parameters")
            .subtitle("Applied in order to the media texture.")
            .params(params)
            .when_some(self.button(Action::Filters), |panel, reset| panel.action(reset))
    }

    fn filter_chain(&self) -> ChainPanel {
        self.filter_steps()
            .into_iter()
            .fold(
                ChainPanel::new("Filter chain").subtitle("What the shader runs for the current values"),
                |panel, (name, detail, active)| panel.step(name, detail, active),
            )
            .note("Steps at their identity value have no effect.")
    }

    /// The filter pipeline in the order it runs: name, value or formula, and whether it changes the image.
    pub(super) fn filter_steps(&self) -> [(&'static str, String, bool); 7] {
        let value = |parameter: Parameter| self.values[parameter as usize];
        let factor = |parameter: Parameter| {
            let v = value(parameter);
            (format!("× {v:.2}"), (v - 1.).abs() > f32::EPSILON)
        };
        let (brightness, brightness_on) = factor(Parameter::Brightness);
        let (saturation, saturation_on) = factor(Parameter::Saturation);
        let contrast = value(Parameter::Contrast);
        let hue = value(Parameter::Hue).rem_euclid(360.);
        let radius = value(Parameter::Radius);
        let opacity = value(Parameter::Opacity);
        let tint = TINT_AMOUNTS[self.tint_index];
        [
            ("Brightness", brightness, brightness_on),
            ("Contrast", format!("(c − 0.5) × {contrast:.2} + 0.5"), (contrast - 1.).abs() > f32::EPSILON),
            ("Saturation", saturation, saturation_on),
            ("Hue rotation", format!("{hue:.1}°"), hue > f32::EPSILON),
            ("Tint", format!("{} · mix {tint:.2}", TINTS[self.tint_index]), tint > 0.),
            ("Corner mask", format!("r {radius:.0} px"), radius > 0.),
            ("Opacity", format!("× {opacity:.2}"), opacity < 1.),
        ]
    }

    /// Badges are the screen's choice: `Soft` for a positive or active state, `Outline` otherwise.
    fn badge(&self, label: &'static str, positive: bool) -> Badge {
        radix::Badge::new(&self.look, label).variant(if positive {
            BadgeVariant::Soft
        } else {
            BadgeVariant::Outline
        })
    }

    pub(super) fn button(&self, action: Action) -> Option<AnyElement> {
        self.buttons
            .iter()
            .find(|(id, _)| *id == action)
            .map(|(_, button)| button.clone().into_any_element())
    }

    pub(super) fn choice(&self, action: Action) -> Option<crate::lab_controls::Choice> {
        self.choices.iter().find(|(id, _)| *id == action).map(|(_, choice)| choice.clone())
    }

    /// Measured pane width from the last frame, so the image fit follows the window.
    fn viewport_width(&self) -> f32 {
        let measured = f32::from(self.bounds[0].size.width);
        if measured > 1. { measured } else { DEFAULT_WIDTH }
    }

    /// Keep the Sweep switch in step with state changed elsewhere (Reset view, drag, reduced motion).
    pub(super) fn sync_switches(&self, cx: &mut Context<Self>) {
        for (action, switch) in &self.state_switches {
            let value = match action {
                Action::Animate => self.animate,
                Action::Wide => self.wide,
                Action::Quality => self.full_quality,
                Action::Pause => self.video_paused,
                _ => false,
            };
            if *switch.read(cx).data() != value {
                switch.update(cx, |switch, cx| switch.set_data(value, cx));
            }
        }
        if *self.sweep_switch.read(cx).data() != self.sweep {
            let sweep = self.sweep;
            self.sweep_switch.update(cx, |switch, cx| switch.set_data(sweep, cx));
        }
    }
}
