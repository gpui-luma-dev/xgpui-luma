//! `V<T>`: a style value that keeps token and field links.
//!
//! Arithmetic on numeric values builds an expression tree instead of computing
//! a number, so a value authored as `CONTROL_HEIGHT * 0.5` stays linked to the
//! token: editing the token updates the value, and editors can show the link.

use std::marker::PhantomData;
use std::ops::{Add, Div, Mul, Sub};

use crate::leaf::{Dyn, Leaf, Numeric};
use crate::resolve::{FieldScope, ResolveCx};
use crate::state::{StateSet, States};

/// The deepest chain of field references followed before giving up (a cycle).
const MAX_DEPTH: u8 = 16;

/// A typed handle to a theme token, such as `palette.focus.ring`.
pub struct Token<T> {
    pub path: &'static str,
    _type: PhantomData<fn() -> T>,
}

impl<T> Token<T> {
    pub const fn new(path: &'static str) -> Self {
        Self { path, _type: PhantomData }
    }
}

impl<T> Clone for Token<T> {
    fn clone(&self) -> Self {
        *self
    }
}
impl<T> Copy for Token<T> {}
impl<T> std::fmt::Debug for Token<T> {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        write!(f, "Token({})", self.path)
    }
}

impl<T: Numeric> Token<T> {
    /// This token, snapped to device pixels when it resolves.
    pub fn snapped(self) -> V<T> {
        V::from(self).snapped()
    }
}

/// A typed handle to another field of the same style struct. Generated by
/// `#[derive(Style)]` as an associated const, such as `CheckboxStyle::INDICATOR_SIZE`.
pub struct Field<T> {
    pub name: &'static str,
    _type: PhantomData<fn() -> T>,
}

impl<T> Field<T> {
    pub const fn new(name: &'static str) -> Self {
        Self { name, _type: PhantomData }
    }
}

impl<T> Clone for Field<T> {
    fn clone(&self) -> Self {
        *self
    }
}
impl<T> Copy for Field<T> {}
impl<T> std::fmt::Debug for Field<T> {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        write!(f, "Field({})", self.name)
    }
}

/// A field whose value is derived in Rust, by a method of the same name on the
/// style. It holds no data; it exists so descriptors and resolved structs
/// include the field.
pub struct Computed<T>(PhantomData<fn() -> T>);

impl<T> Default for Computed<T> {
    fn default() -> Self {
        Self(PhantomData)
    }
}
impl<T> Clone for Computed<T> {
    fn clone(&self) -> Self {
        Self::default()
    }
}
impl<T> PartialEq for Computed<T> {
    fn eq(&self, _: &Self) -> bool {
        true
    }
}
impl<T> std::fmt::Debug for Computed<T> {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.write_str("Computed")
    }
}

/// Binary operators in numeric expressions.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum Op {
    Add,
    Sub,
    Mul,
    Div,
    Min,
    Max,
}

/// A numeric expression. Units are checked by the Rust types that build it.
#[derive(Clone, Debug, PartialEq)]
pub enum NumExpr {
    Lit(f32),
    Token(&'static str),
    Field(&'static str),
    Bin(Op, Box<NumExpr>, Box<NumExpr>),
    /// Round to the nearest device pixel at the resolve scale factor.
    Snap(Box<NumExpr>),
}

impl NumExpr {
    fn eval(&self, cx: &ResolveCx<'_>, scope: &dyn FieldScope, at: StateSet, depth: u8) -> f32 {
        let number = |value: Option<Dyn>, what: &dyn std::fmt::Display| match value {
            Some(Dyn::Number(number)) => number,
            Some(other) => {
                cx.error(format!("{what} is not a number: {other:?}"));
                0.0
            }
            None => {
                cx.error(format!("{what} is missing"));
                0.0
            }
        };
        match self {
            NumExpr::Lit(value) => *value,
            NumExpr::Token(path) => number(cx.token(path), &format_args!("token `{path}`")),
            NumExpr::Field(name) => number(follow(cx, scope, name, at, depth), &format_args!("field `{name}`")),
            NumExpr::Snap(inner) => cx.snap(inner.eval(cx, scope, at, depth)),
            NumExpr::Bin(op, a, b) => {
                let (a, b) = (a.eval(cx, scope, at, depth), b.eval(cx, scope, at, depth));
                match op {
                    Op::Add => a + b,
                    Op::Sub => a - b,
                    Op::Mul => a * b,
                    Op::Div if b == 0.0 => {
                        cx.error("division by zero".into());
                        0.0
                    }
                    Op::Div => a / b,
                    Op::Min => a.min(b),
                    Op::Max => a.max(b),
                }
            }
        }
    }
}

impl std::fmt::Display for NumExpr {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            NumExpr::Lit(value) => write!(f, "{value}"),
            NumExpr::Token(path) => f.write_str(path),
            NumExpr::Field(name) => write!(f, "self.{name}"),
            NumExpr::Snap(inner) => write!(f, "snap({inner})"),
            NumExpr::Bin(Op::Min, a, b) => write!(f, "min({a}, {b})"),
            NumExpr::Bin(Op::Max, a, b) => write!(f, "max({a}, {b})"),
            NumExpr::Bin(op, a, b) => {
                let symbol = match op {
                    Op::Add => "+",
                    Op::Sub => "-",
                    Op::Mul => "*",
                    _ => "/",
                };
                write!(f, "({a} {symbol} {b})")
            }
        }
    }
}

fn follow(cx: &ResolveCx<'_>, scope: &dyn FieldScope, name: &str, at: StateSet, depth: u8) -> Option<Dyn> {
    if depth >= MAX_DEPTH {
        cx.error(format!("field reference cycle at `{name}`"));
        return None;
    }
    scope.field(name, cx, at, depth + 1)
}

/// A style value: a literal, a token, another field, or (for numeric types)
/// an expression.
#[derive(Clone, Debug, PartialEq)]
pub enum V<T> {
    Lit(T),
    Token(&'static str),
    Field(&'static str),
    Num(Box<NumExpr>),
}

impl<T: Leaf> Default for V<T> {
    fn default() -> Self {
        V::Lit(T::default())
    }
}

impl<T: Leaf> V<T> {
    /// Evaluate against the tokens and the owning struct. Failures are recorded
    /// on `cx` and fall back to the type's default.
    pub fn eval(&self, cx: &ResolveCx<'_>, scope: &dyn FieldScope, at: StateSet, depth: u8) -> T {
        let found = match self {
            V::Lit(value) => return value.clone(),
            V::Token(path) => cx.token(path).map(|value| (value, format!("token `{path}`"))),
            V::Field(name) => follow(cx, scope, name, at, depth).map(|value| (value, format!("field `{name}`"))),
            V::Num(expr) => Some((Dyn::Number(expr.eval(cx, scope, at, depth)), format!("`{expr}`"))),
        };
        match found {
            Some((value, what)) => T::from_dyn(&value).unwrap_or_else(|| {
                cx.error(format!("{what} has the wrong type for {:?}: {value:?}", T::KIND.value));
                T::default()
            }),
            None => {
                if let V::Token(path) = self {
                    cx.error(format!("token `{path}` is missing"));
                }
                T::default()
            }
        }
    }

    /// A short description for editors: the literal, token path, or expression.
    pub fn describe(&self) -> String {
        match self {
            V::Lit(value) => format!("{value:?}"),
            V::Token(path) => (*path).to_owned(),
            V::Field(name) => format!("self.{name}"),
            V::Num(expr) => expr.to_string(),
        }
    }

    /// Whether this value is linked to a token, field, or expression.
    pub fn is_linked(&self) -> bool {
        !matches!(self, V::Lit(_))
    }
}

impl<T: Numeric> V<T> {
    fn expr(self) -> NumExpr {
        match self {
            V::Lit(value) => NumExpr::Lit(value.to_f32()),
            V::Token(path) => NumExpr::Token(path),
            V::Field(name) => NumExpr::Field(name),
            V::Num(expr) => *expr,
        }
    }

    /// Snap the value to device pixels when it resolves. Use it where a value
    /// comes from the control scale; literals and authored values stay exact.
    pub fn snapped(self) -> V<T> {
        V::Num(Box::new(NumExpr::Snap(Box::new(self.expr()))))
    }

    pub fn max(self, other: impl Into<V<T>>) -> V<T> {
        V::Num(Box::new(NumExpr::Bin(Op::Max, Box::new(self.expr()), Box::new(other.into().expr()))))
    }

    pub fn min(self, other: impl Into<V<T>>) -> V<T> {
        V::Num(Box::new(NumExpr::Bin(Op::Min, Box::new(self.expr()), Box::new(other.into().expr()))))
    }
}

impl<T: Leaf> From<T> for V<T> {
    fn from(value: T) -> Self {
        V::Lit(value)
    }
}

impl<T: Leaf> From<Token<T>> for V<T> {
    fn from(token: Token<T>) -> Self {
        V::Token(token.path)
    }
}

impl<T: Leaf> From<Field<T>> for V<T> {
    fn from(field: Field<T>) -> Self {
        V::Field(field.name)
    }
}

/// A right-hand operand for `*` and `/`: a plain number or any numeric value.
/// Scaling keeps the left side's unit (`Px * Scalar` is `Px`).
pub trait Factor {
    fn factor(self) -> NumExpr;
}

impl Factor for f32 {
    fn factor(self) -> NumExpr {
        NumExpr::Lit(self)
    }
}

impl<U: Numeric> Factor for V<U> {
    fn factor(self) -> NumExpr {
        self.expr()
    }
}

impl<U: Numeric> Factor for Token<U> {
    fn factor(self) -> NumExpr {
        NumExpr::Token(self.path)
    }
}

impl<U: Numeric> Factor for Field<U> {
    fn factor(self) -> NumExpr {
        NumExpr::Field(self.name)
    }
}

macro_rules! numeric_ops {
    ($($ty:ident),*) => {$(
        impl<T: Numeric, R: Factor> Mul<R> for $ty<T> {
            type Output = V<T>;
            fn mul(self, rhs: R) -> V<T> {
                V::Num(Box::new(NumExpr::Bin(Op::Mul, Box::new(V::from(self).expr()), Box::new(rhs.factor()))))
            }
        }

        impl<T: Numeric, R: Factor> Div<R> for $ty<T> {
            type Output = V<T>;
            fn div(self, rhs: R) -> V<T> {
                V::Num(Box::new(NumExpr::Bin(Op::Div, Box::new(V::from(self).expr()), Box::new(rhs.factor()))))
            }
        }

        impl<T: Numeric, R: Into<V<T>>> Add<R> for $ty<T> {
            type Output = V<T>;
            fn add(self, rhs: R) -> V<T> {
                V::Num(Box::new(NumExpr::Bin(Op::Add, Box::new(V::from(self).expr()), Box::new(rhs.into().expr()))))
            }
        }

        impl<T: Numeric, R: Into<V<T>>> Sub<R> for $ty<T> {
            type Output = V<T>;
            fn sub(self, rhs: R) -> V<T> {
                V::Num(Box::new(NumExpr::Bin(Op::Sub, Box::new(V::from(self).expr()), Box::new(rhs.into().expr()))))
            }
        }
    )*};
}

numeric_ops!(V, Token, Field);

/// A value with no paint (`Option<T>` fields).
pub fn none<T: Leaf>() -> V<Option<T>>
where
    Option<T>: Leaf,
{
    V::Lit(None)
}

/// Build a [`States`] table of values.
impl<T: Leaf> States<V<T>> {
    pub fn new(base: impl Into<V<T>>) -> Self {
        States::base(base.into())
    }

    /// Add or replace the rule for `at`.
    pub fn on(mut self, at: impl Into<StateSet>, value: impl Into<V<T>>) -> Self {
        self.set(at.into(), value.into());
        self
    }
}

impl<T: Leaf> From<T> for States<V<T>> {
    fn from(value: T) -> Self {
        States::new(value)
    }
}

impl<T: Leaf> From<Token<T>> for States<V<T>> {
    fn from(token: Token<T>) -> Self {
        States::new(token)
    }
}

impl<T: Leaf> From<V<T>> for States<V<T>> {
    fn from(value: V<T>) -> Self {
        States::base(value)
    }
}
